type MessageValues = Record<string, string | number>

function interpolate(message: string, values?: MessageValues) {
  if (!values) return message
  return message.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))
}

function detectInitialLocale(): AppLocale {
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored === 'en' || stored === 'fr') return stored
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

interface I18nContextValue {
  locale: AppLocale
  setLocale(locale: AppLocale): void
  t(message: string, values?: MessageValues): string
  formatDate(value: string | Date, options?: Intl.DateTimeFormatOptions): string
}

const defaultContext: I18nContextValue = {
  locale: 'en',
  setLocale: () => undefined,
  t: interpolate,
  formatDate: (date, options) => new Intl.DateTimeFormat('en', options).format(typeof date === 'string' ? new Date(date) : date),
}

const I18nContext = createContext<I18nContextValue>(defaultContext)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<AppLocale>(detectInitialLocale)

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale)
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (message, values) => interpolate(locale === 'fr' ? frenchMessages[message] ?? message : message, values),
    formatDate: (date, options) => new Intl.DateTimeFormat(locale, options).format(typeof date === 'string' ? new Date(date) : date),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
